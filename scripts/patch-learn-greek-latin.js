function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function main() {
  let src = fs.readFileSync(FILE, 'utf8');

  src = src.replace(
    /Glossário PT → EN\/ES\/FR\/IT\/DE\/YO\/SW\/GEZ para o modo Aprender \(palavra a palavra\)\./,
    'Glossário PT → EN/ES/FR/IT/DE/YO/SW/GEZ/EL/LA para o modo Aprender (palavra a palavra).'
  );

  let patched = 0;
  let missing = [];

  // Entradas com yo/sw/gez (formato actual)
  src = src.replace(
    /^(\s{4})([a-zàáâãäåæçèéêëìíîïñòóôõöùúûüýÿœ0-9_'-]+):\s*\{\s*((?:[^}]|\}(?!\s*,?\s*$))*)\s*\}/gim,
    (full, indent, key, inner) => {
      if (!/\ben:\s*'/.test(inner)) return full;
      if (/\bel:\s*'/.test(inner) && /\bla:\s*'/.test(inner)) return full;

      const c = CLASSICAL[key];
      let el;
      let la;
      if (c) {
        patched += 1;
        el = c.el;
        la = c.la;
      } else {
        missing.push(key);
        const enM = inner.match(/\ben:\s*'((?:\\'|[^'])*)'/);
        const en = enM ? enM[1] : key;
        el = en;
        la = en;
      }

      let next = inner.replace(/,\s*$/, '').trim();
      if (/\bel:\s*'/.test(next)) {
        next = next.replace(/\bel:\s*'((?:\\'|[^'])*)'/, `el: '${esc(el)}'`);
      } else {
        next += `, el: '${esc(el)}'`;
      }
      if (/\bla:\s*'/.test(next)) {
        next = next.replace(/\bla:\s*'((?:\\'|[^'])*)'/, `la: '${esc(la)}'`);
      } else {
        next += `, la: '${esc(la)}'`;
      }
      return `${indent}${key}: { ${next} }`;
    }
  );

  if (!src.includes("if (lang === 'el')")) {
    src = src.replace(
      /if \(lang === 'gez'\) return entry\.gez \|\| entry\.en \|\| '';\s*\n\s*return entry\.en/,
      "if (lang === 'gez') return entry.gez || entry.en || '';\n" +
        "    if (lang === 'el') return entry.el || entry.en || '';\n" +
        "    if (lang === 'la') return entry.la || entry.en || '';\n" +
        '    return entry.en'
    );
  }

  // Garante entradas novas (simbiose / étimo) se ainda não existirem
  const extras = ['simbiose', 'simbionte', 'étimo', 'etimo', 'grego', 'latim'];
  for (const key of extras) {
    const re = new RegExp(`^\\s{4}${key}:\\s*\\{`, 'm');
    if (re.test(src)) continue;
    const c = CLASSICAL[key];
    if (!c) continue;
    const block =
      `    ${key}: { en: '${esc(c.la === 'symbiosis' ? 'symbiosis' : c.la)}', ` +
      `es: '${esc(c.la)}', fr: '${esc(c.la)}', it: '${esc(c.la)}', de: '${esc(c.la)}', ` +
      `yo: '${esc(c.la)}', sw: '${esc(c.la)}', gez: '${esc(c.la)}', ` +
      `el: '${esc(c.el)}', la: '${esc(c.la)}' },\n`;
    src = src.replace(
      /(\n\s{2}\};\n\n\s*function stripAccents)/,
      `\n${block}$1`
    );
  }

  fs.writeFileSync(FILE, src, 'utf8');
  console.log('Patched Greek/Latin translations:', patched);
  console.log('Fallback-to-EN keys:', missing.length);
  if (missing.length && missing.length <= 40) console.log(missing.join(', '));
}

main();
