function writeLocales() {
  const written = [];
  for (const code of Object.keys(META)) {
    const pack = LOCALES[code];
    if (!pack) {
      throw new Error('Missing translations for locale: ' + code);
    }
    const data = {
      meta: META[code],
      common: pack.common,
      radio: pack.radio,
      posts: pack.posts,
      nav: pack.nav,
      footer: pack.footer,
      pages: pack.pages,
    };
    if (Object.prototype.hasOwnProperty.call(data, 'menu')) {
      throw new Error(code + ' must not include a menu key');
    }
    const dest = path.join(OUT_DIR, code + '.json');
    fs.writeFileSync(dest, JSON.stringify(data, null, 2) + '\n', 'utf8');
    written.push(dest);
    console.log('wrote ' + dest);
  }
  return written;
}

