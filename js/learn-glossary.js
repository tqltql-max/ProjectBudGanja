  function stripAccents(s) {
    return String(s || '')
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
  }

  function normalizeKey(raw) {
    return String(raw || '')
      .trim()
      .toLowerCase()
      .replace(/^[«»"'“”‘’(\[]+|[)»»"'“”‘’)\],.:;!?…]+$/g, '');
  }

  function lookup(word, lang) {
    var key = normalizeKey(word);
    if (!key) return '';
    var entry = GLOSSARY[key];
    if (!entry) {
      var bare = stripAccents(key);
      if (bare !== key) entry = GLOSSARY[bare];
      if (!entry) {
        for (var k in GLOSSARY) {
          if (Object.prototype.hasOwnProperty.call(GLOSSARY, k) && stripAccents(k) === bare) {
            entry = GLOSSARY[k];
            break;
          }
        }
      }
    }
    if (!entry) return '';
    if (lang === 'es') return entry.es || entry.en || '';
    if (lang === 'fr') return entry.fr || entry.en || '';
    if (lang === 'it') return entry.it || entry.en || '';
    if (lang === 'de') return entry.de || entry.en || '';
    return entry.en || entry.es || '';
  }

  function has(word) {
    return !!lookup(word, 'en');
  }

  var TOKEN_RE = /([A-Za-zÀ-ÿ]+(?:['’-][A-Za-zÀ-ÿ]+)?)|([^A-Za-zÀ-ÿ]+)/g;

  function translatePhrase(text, lang) {
    if (!text) return '';
    TOKEN_RE.lastIndex = 0;
    var out = '';
    var m;
    while ((m = TOKEN_RE.exec(String(text))) !== null) {
      if (m[1]) out += lookup(m[1], lang) || m[1];
      else if (m[2]) out += m[2];
    }
    return out;
  }

