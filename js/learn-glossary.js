  function stripAccents(s) {
    return String(s || '')
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
  }

  function normalizeKey(raw) {
    return String(raw || '')
      .trim()
      .toLowerCase()
      .replace(/^[«»"'“”‘’(\[]+|[)»»"'“”‘’)\],.:;!?…]+$/g, '');
  }

  function lookup(word, lang) {
    var key = normalizeKey(word);
    if (!key) return '';
    var entry = GLOSSARY[key];
    if (!entry) {
      var bare = stripAccents(key);
      if (bare !== key) entry = GLOSSARY[bare];
      if (!entry) {
        for (var k in GLOSSARY) {
          if (Object.prototype.hasOwnProperty.call(GLOSSARY, k) && stripAccents(k) === bare) {
            entry = GLOSSARY[k];
            break;
          }
        }
      }
    }
    if (!entry) return '';
    if (lang === 'es') return entry.es || entry.en || '';
    return entry.en || entry.es || '';
  }

  function has(word) {
    return !!lookup(word, 'en');
  }

