'use strict';

/**
 * Poema de encerramento da página Vida.
 * Título fixo (pedido do laboratório): «A semente foi plantada».
 */

function poemSementeFoiPlantadaPt() {
  return `A semente foi plantada.
Não pedimos flor hoje —
pedimos só o ofício:
mão na terra,
água certa,
ficar.

A Dona Maria fez a cama.
O Inspetor mediu a luz.
A Joana ficou de guarda.
Os passarinhos cantaram
como quem diz:
já está.

Dizem que plantar é o fim da espera.
Mentira doce.
Plantar é o início —
a semente some da mão
para aparecer no tempo.

Não se força o broto.
Espera-se o torrão.
Conta-se a gota.
Cumprimenta-se o inverno
quando ele chega cedo demais.

O laboratório não apressa a terra.
Planta à beira.
Conta gotas.
Chama a Vida pelo nome verdadeiro:
ficar.

Faça o melhor!

Porque toda semente que permanece
quando a terra fecha em volta
cresce um pouco no mapa:
uma raiz a mais,
um verso a mais,
um nós onde antes só havia
semente na palma.`;
}

function poemSementeFoiPlantadaEn() {
  return `The seed was planted.
We do not ask for flower today —
we ask only for the craft:
hand in the soil,
right water,
stay.

Dona Maria made the bed.
The Inspector measured the light.
Joana kept watch.
The little birds sang
as if to say:
it is already done.

They say planting is the end of waiting.
Sweet lie.
Planting is the beginning —
the seed leaves the hand
to appear in time.

Do not force the sprout.
Wait for the root ball.
Count the drop.
Greet winter
when it arrives too soon.

The laboratory does not rush the earth.
It plants at the edge.
It counts drops.
It calls Vida by its true name:
stay.

Do your best!

Because every seed that remains
when the soil closes around it
grows a little on the map:
one more root,
one more verse,
a we where once there was only
a seed in the palm.`;
}

function poemSementeFoiPlantadaEs() {
  return `La semilla fue plantada.
No pedimos flor hoy —
pedimos solo el oficio:
mano en la tierra,
agua justa,
quedarse.

Doña Maria hizo la cama.
El Inspector midió la luz.
Joana quedó de guardia.
Los pajaritos cantaron
como quien dice:
ya está.

Dicen que plantar es el fin de la espera.
Mentira dulce.
Plantar es el inicio —
la semilla sale de la mano
para aparecer en el tiempo.

No se fuerza el brote.
Se espera el cepellón.
Se cuenta la gota.
Se saluda al invierno
cuando llega demasiado pronto.

El laboratorio no apresura la tierra.
Siembra a la orilla.
Cuenta gotas.
Llama a Vida por su nombre verdadero:
quedarse.

¡Haz lo mejor!

Porque toda semilla que permanece
cuando la tierra cierra alrededor
crece un poco en el mapa:
una raíz más,
un verso más,
un nosotros donde antes solo había
semilla en la palma.`;
}

module.exports = {
  poemSementeFoiPlantadaPt,
  poemSementeFoiPlantadaEn,
  poemSementeFoiPlantadaEs
};
