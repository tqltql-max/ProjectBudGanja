function getFungoNoteMeta(slug, loc) {
  const entry = NOTES[slug];
  if (!entry) return null;
  const block = entry[loc] || entry['pt-BR'];
  if (!block) return null;
  return { titleSuffix: block.titleSuffix, excerpt: block.excerpt };
}

function renderFungoNotes(slug, loc) {
  const entry = NOTES[slug];
  if (!entry) return '';
  const block = entry[loc] || entry['pt-BR'];
  if (!block || !block.markdown) return '';
  return '\n' + block.markdown + '\n';
}

module.exports = { getFungoNoteMeta, renderFungoNotes };
